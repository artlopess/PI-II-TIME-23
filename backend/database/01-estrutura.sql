-- ============================================================
-- PROJETOS
-- Toda demanda pertence obrigatoriamente a um projeto.
-- ============================================================
CREATE TABLE projetos (
    id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR2(100) NOT NULL
);


-- ============================================================
-- USUARIOS
-- Os tres perfis previstos no escopo. A senha e guardada como
-- hash, nunca em texto puro.
-- ============================================================
CREATE TABLE usuarios (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR2(100) NOT NULL,
    email       VARCHAR2(150) NOT NULL UNIQUE,
    senha_hash  VARCHAR2(255) NOT NULL,
    perfil      VARCHAR2(30)  NOT NULL,

    -- O CHECK faz o proprio banco recusar um perfil invalido,
    -- mesmo que a API deixe passar por engano.
    CONSTRAINT ck_usuarios_perfil CHECK (
        perfil IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe')
    )
);


-- ============================================================
-- DEMANDAS
-- Tabela central do sistema.
-- ============================================================
CREATE TABLE demandas (
    id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo             VARCHAR2(120) NOT NULL,
    descricao          VARCHAR2(2000) NOT NULL,
    tipo               VARCHAR2(20)  NOT NULL,
    prioridade         VARCHAR2(15)  NOT NULL,
    status             VARCHAR2(20)  NOT NULL,
    projeto_id         NUMBER        NOT NULL,

    -- Pode ficar nulo: a demanda nasce sem responsavel definido
    responsavel_id     NUMBER,

    data_criacao       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    data_atualizacao   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,

    -- Pode ficar nulo: o prazo e opcional
    prazo              DATE,

    -- Os valores aceitos sao exatamente os do documento de escopo
    CONSTRAINT ck_demandas_tipo CHECK (
        tipo IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')
    ),
    CONSTRAINT ck_demandas_prioridade CHECK (
        prioridade IN ('Crítica', 'Alta', 'Média', 'Baixa')
    ),
    CONSTRAINT ck_demandas_status CHECK (
        status IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada')
    ),

    -- Liga a demanda ao projeto e ao responsavel
    CONSTRAINT fk_demandas_projeto
        FOREIGN KEY (projeto_id) REFERENCES projetos (id),
    CONSTRAINT fk_demandas_responsavel
        FOREIGN KEY (responsavel_id) REFERENCES usuarios (id)
);


-- ============================================================
-- COMENTARIOS
-- Cada comentario pertence a uma demanda e a um usuario (item 2.2.6).
-- ============================================================
CREATE TABLE comentarios (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id  NUMBER         NOT NULL,
    usuario_id  NUMBER         NOT NULL,
    texto       VARCHAR2(2000) NOT NULL,
    data_hora   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,

    -- ON DELETE CASCADE: se a demanda sumir, os comentarios somem junto.
    -- Na pratica demandas nao sao excluidas, mas a regra protege o banco.
    CONSTRAINT fk_comentarios_demanda
        FOREIGN KEY (demanda_id) REFERENCES demandas (id) ON DELETE CASCADE,
    CONSTRAINT fk_comentarios_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);


-- ============================================================
-- HISTORICO
-- Registra automaticamente quem alterou o que (item 2.2.7).
-- O historico nunca e apagado.
-- ============================================================
CREATE TABLE historico (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id      NUMBER        NOT NULL,
    usuario_id      NUMBER        NOT NULL,

    -- Qual campo mudou: 'status', 'responsavel', 'prioridade', 'prazo'
    campo           VARCHAR2(30)  NOT NULL,

    valor_anterior  VARCHAR2(200),
    valor_novo      VARCHAR2(200),
    data_hora       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT fk_historico_demanda
        FOREIGN KEY (demanda_id) REFERENCES demandas (id),
    CONSTRAINT fk_historico_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);


-- ============================================================
-- INDICES
-- Deixam as consultas da listagem e do dashboard mais rapidas.
-- ============================================================
CREATE INDEX ix_demandas_status     ON demandas (status);
CREATE INDEX ix_demandas_prioridade ON demandas (prioridade);
CREATE INDEX ix_demandas_projeto    ON demandas (projeto_id);
CREATE INDEX ix_comentarios_demanda ON comentarios (demanda_id);
CREATE INDEX ix_historico_demanda   ON historico (demanda_id);

COMMIT;